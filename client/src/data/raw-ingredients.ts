export function calculateIngredientMacros(
  ingredient: RawIngredient,
  amount: number,
  unit: string
): { kcal: number; p: number; c: number; f: number; totalGrams: number } {
  let totalGrams = amount;
  if (unit === "pieces" || unit === "scoops" || unit === "tbsp") {
    totalGrams = amount * ingredient.unitWeightInGrams;
  } else if (unit === "ml") {
    totalGrams = amount;
  }

  const factor = totalGrams / 100;
  return {
    kcal: Math.round(ingredient.kcalPer100g * factor),
    p: Math.round(ingredient.pPer100g * factor * 10) / 10,
    c: Math.round(ingredient.cPer100g * factor * 10) / 10,
    f: Math.round(ingredient.fPer100g * factor * 10) / 10,
    totalGrams: Math.round(totalGrams),
  };
}
